"""A dirty code document survives a process restart, including an empty one."""
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from haumea_test_env import editor_env, run_editor
from test_ui_scripts import BINARY, XVFB, start_xvfb

HERE = Path(__file__).resolve().parent


@unittest.skipUnless(BINARY and XVFB, 'needs the editor and Xvfb')
class PawnEditorRecoveryTests(unittest.TestCase):
    def test_recover_manual_code_after_restart(self):
        with tempfile.TemporaryDirectory(prefix='haumea-code-') as tmp:
            work = Path(tmp)
            game = work / 'game'
            subprocess.run([sys.executable, str(HERE / 'fixture/make_game.py'), str(game)],
                           check=True, capture_output=True)
            env = editor_env(work, virtual_display=True)
            xvfb, env['DISPLAY'] = start_xvfb()
            env.pop('XAUTHORITY', None)
            script = work / 'code.uis'

            def play(source):
                script.write_text(source)
                result = run_editor([BINARY, '--game', game, '--workspace', work,
                                     '--ui-script', script], cwd=work, env=env)
                self.assertEqual(result.returncode, 0, result.stdout)

            try:
                play('''wait 10
click_item '*' 'Code'
wait 5
click 500 300
key Ctrl+Home
type "// recovered manual code"
wait 100
assert ide_dirty == 1
''')
                draft = Path(env['XDG_CONFIG_HOME'], 'haumea/pawn-ide/draft.pwn')
                self.assertIn('// recovered manual code', draft.read_text())
                play('''wait 10
click_item '*' 'Code'
wait 5
assert ide_dirty == 1
assert ide_contains '// recovered manual code'
click 500 300
key Ctrl+A
key Backspace
wait 100
assert ide_dirty == 1
''')
                self.assertEqual(draft.read_text(), '')
                play('''wait 10
click_item '*' 'Code'
wait 5
assert ide_dirty == 1
assert ide_lacks '// recovered manual code'
assert ide_lacks 'Generated by'
''')
            finally:
                xvfb.terminate()
                xvfb.wait(10)


if __name__ == '__main__':
    unittest.main()
