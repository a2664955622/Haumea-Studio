#!/usr/bin/env python3
#
# gen_icon.py
# Renders assets/haumea-mark.svg at the window icon sizes and writes
# haumea_icon.h (RGBA pixels for glfwSetWindowIcon). Needs rsvg-convert
# and ImageMagick's magick.
#

import os
import subprocess
import tempfile

SIZES = [16, 32, 48, 64, 128]

here = os.path.dirname(os.path.abspath(__file__))
svg = os.path.join(here, '..', '..', 'assets', 'haumea-mark.svg')

out = ['// Generated by gen_icon.py from assets/haumea-mark.svg; do not edit.',
	'// RGBA window icon images, largest last.', '', '#pragma once', '']
with tempfile.TemporaryDirectory() as tmp:
	for size in SIZES:
		png = os.path.join(tmp, '%d.png' % size)
		subprocess.run(['rsvg-convert', '-w', str(size), '-h', str(size), '-o', png, svg], check=True)
		rgba = subprocess.run(['magick', png, '-depth', '8', 'RGBA:-'], check=True,
			capture_output=True).stdout
		assert len(rgba) == size * size * 4
		out.append('static const unsigned char haumeaIcon%d[%d] = {' % (size, len(rgba)))
		for i in range(0, len(rgba), 24):
			out.append('\t' + ','.join(str(b) for b in rgba[i:i+24]) + ',')
		out.append('};')
		out.append('')
out.append('static const struct { int size; const unsigned char *pixels; } haumeaIcons[] = {')
for size in SIZES:
	out.append('\t{ %d, haumeaIcon%d },' % (size, size))
out.append('};')
out.append('')
with open(os.path.join(here, 'haumea_icon.h'), 'w') as f:
	f.write('\n'.join(out))
print('wrote haumea_icon.h')
