# gen_anim_ids.py <open.mp>/SDK/include/anim.hpp
# Writes anim_ids.h: the client's animation index table ("LIB:NAME" per ID,
# as GetAnimationName and on-foot sync data use it), from open.mp's SDK
# (Mozilla Public License 2.0).
#

import os
import re
import sys

names = []
inTable = False
for line in open(sys.argv[1], encoding='utf-8'):
	if 'AnimationNames[]' in line:
		inTable = True
		continue
	if inTable:
		if line.strip().startswith('};'):
			break
		m = re.match(r'\s*"([^"]*)",?', line)
		if m:
			names.append(m.group(1))

out = ['// Generated by gen_anim_ids.py from open.mp\'s SDK/include/anim.hpp',
	'// (Mozilla Public License 2.0); do not edit. Index = animation ID.', '', '#pragma once', '',
	'static const char *const sampAnimationNames[] = {']
for n in names:
	out.append('\t"%s",' % n)
out.append('};')
out.append('')
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'anim_ids.h'), 'w') as f:
	f.write('\n'.join(out))
print('wrote anim_ids.h (%d animations)' % len(names))
