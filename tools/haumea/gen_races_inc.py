# gen_races_inc.py: writes haumea_races_inc.h from haumea_races.inc, so the
# editor can write the include beside a test gamemode or into a workspace.
# Run it again after changing haumea_races.inc.
#

import os

here = os.path.dirname(os.path.abspath(__file__))
text = open(os.path.join(here, 'haumea_races.inc'), encoding='utf-8').read()
# MSVC caps one string literal near 16 KB: split it into pieces.
pieces, piece = [], ''
for line in text.splitlines(keepends=True):
	if len(piece) + len(line) > 8000:
		pieces.append(piece)
		piece = ''
	piece += line
pieces.append(piece)
with open(os.path.join(here, 'haumea_races_inc.h'), 'w', encoding='utf-8', newline='\n') as out:
	out.write('// Generated by gen_races_inc.py from haumea_races.inc; do not edit.\n')
	out.write('#pragma once\n\n')
	out.write('static const char *const kHaumeaRacesInc[] = {\n')
	for p in pieces:
		assert ')HRI"' not in p
		out.write('R"HRI(' + p + ')HRI",\n')
	out.write('};\n')
