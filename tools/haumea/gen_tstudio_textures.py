# gen_tstudio_textures.py <Texture Studio>/filterscripts/tstudio/alltextures.pwn
# Writes tstudio_textures.h: Texture Studio's ObjectTextures table, in its
# order, because Texture Studio maps store materials as indices into it.
# Kept exactly as Texture Studio's list for that reason, and credited in
# THIRD_PARTY_NOTICES.md; the editor prefers a workspace's own alltextures.pwn.
#

import os
import re
import sys

src = sys.argv[1]
entry = re.compile(r'^\s*\{\s*(-?\d+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*\}')
rows = []
inTable = False
for line in open(src, encoding='latin-1'):
	if 'ObjectTextures[][TEXTUREDEF]' in line:
		inTable = True
		continue
	if inTable:
		if line.strip().startswith('};'):
			break
		m = entry.match(line)
		if m:
			rows.append((int(m.group(1)), m.group(2), m.group(3)))

out = ['// Generated by gen_tstudio_textures.py from Texture Studio\'s alltextures.pwn;',
	'// do not edit. Index 0 means "no texture".',
	'// Kept exactly as Texture Studio\'s list (credited in THIRD_PARTY_NOTICES.md):',
	'// its .db maps store textures by this index, so the order must not change.', '', '#pragma once', '',
	'static const TStudioTexture tstudioTextures[] = {']
for model, txd, tex in rows:
	out.append('\t{ %d, "%s", "%s" },' % (model, txd, tex))
out.append('};')
out.append('')
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'tstudio_textures.h'), 'w') as f:
	f.write('\n'.join(out))
print('wrote tstudio_textures.h (%d textures)' % len(rows))
