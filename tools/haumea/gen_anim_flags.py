# gen_anim_flags.py <path/to/animation_catalog.h>
# Writes anim_flags.h: the animations a ped skin can't play (they move only
# an object's parts) and the ones that deform it.
#

import os
import re
import sys

text = open(sys.argv[1], encoding='utf-8').read()
libs = re.search(r'Libraries\[\]\s*=\s*\{(.*?)\};', text, re.S).group(1)
libs = re.findall(r'"([^"]+)"', libs)
entry = re.compile(r'\{\s*\d+\s*,\s*(\d+)\s*,\s*"([^"]+)"\s*,\s*\d+\s*,\s*[\d.]+f\s*,\s*Missing::(\w+)\s*(?:,\s*(true|false))?\s*\}')
rows = []
for lib, name, missing, bugged in entry.findall(text):
	objectOnly = missing == 'ObjectOnly'
	deforms = bugged == 'true'
	if objectOnly or deforms:
		rows.append((libs[int(lib)].upper(), name.upper(), objectOnly, deforms))
rows.sort()
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'anim_flags.h'), 'w', encoding='utf-8', newline='\n') as out:
	out.write('// Generated by gen_anim_flags.py from animation_catalog.h; do not edit.\n'
		'// Sorted by library, then name, upper case.\n\n#pragma once\n\n'
		'struct AnimFlagEntry { const char *lib, *name; bool objectOnly, deforms; };\n'
		'static const AnimFlagEntry animFlagEntries[] = {\n')
	for lib, name, objectOnly, deforms in rows:
		out.write('\t{ "%s", "%s", %s, %s },\n' % (lib, name, 'true' if objectOnly else 'false', 'true' if deforms else 'false'))
	out.write('};\n')
print(len(rows), 'animations', sum(r[2] for r in rows), 'object only', sum(r[3] for r in rows), 'deform')
